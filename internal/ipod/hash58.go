func lcm(a, b byte) int {
	if a == 0 || b == 0 {
		return 1
	}
	return int(a) * int(b) / gcd(int(a), int(b))
}

func gcd(a, b int) int {
	for b != 0 {
		a, b = b, a%b
	}
	return a
}

// generateKey derives the 64-byte HMAC key from the first 8 raw bytes of the
// decoded FireWire GUID.
func generateKey(fw []byte) [64]byte {
	var y [16]byte
	for i := 0; i < 4; i++ {
		l := lcm(fw[2*i], fw[2*i+1])
		hi, lo := byte(l>>8), byte(l&0xff)
		y[4*i+0], y[4*i+1] = aesSbox[hi], aesInvSbox[hi]
		y[4*i+2], y[4*i+3] = aesSbox[lo], aesInvSbox[lo]
	}
	var combo [18 + 16]byte
	copy(combo[:], fixed[:])
	copy(combo[18:], y[:])
	h := sha1.Sum(combo[:])
	var key [64]byte
	copy(key[:], h[:])
	return key
}

func computeHash58(fw, itdb []byte) [20]byte {
	key := generateKey(fw)
	var ipad, opad [64]byte
	for i := range key {
		ipad[i] = key[i] ^ 0x36
		opad[i] = key[i] ^ 0x5c
	}
	h := sha1.New()
	h.Write(ipad[:])
	h.Write(itdb)
	inner := h.Sum(nil)
	h.Reset()
	h.Write(opad[:])
	h.Write(inner)
	var out [20]byte
	copy(out[:], h.Sum(nil))
	return out
}

// writeHash58 computes and stores the HASH58 checksum in place. itdb must be
// an "mhbd" database with at least a 0xF4-byte header. Following libgpod it
// zeroes db_id (0x18) and unk_0x32 (0x32) during computation, sets
// hashing_scheme (0x30) = 1, and leaves hash72/hashAB untouched in the
// message. fw is the raw 8-byte FireWire GUID (first 8 bytes of the decoded
// 16-byte GUID) from the device's SysInfo/SysInfoExtended.
func writeHash58(itdb []byte, fw []byte) error {
	const mhbdHeaderSize = 0xF4
	if len(itdb) < mhbdHeaderSize {
		return fmt.Errorf("database too short for HASH58 header (%d < 0xF4)", len(itdb))
	}
	if string(itdb[:4]) != "mhbd" {
		return fmt.Errorf("not an mhbd database")
	}
	if len(fw) < 8 {
		return fmt.Errorf("FireWire GUID too short for HASH58")
	}

	dbID := append([]byte(nil), itdb[0x18:0x20]...)
	unk32 := append([]byte(nil), itdb[0x32:0x46]...)

	clear(itdb[0x18:0x20])
	clear(itdb[0x32:0x46])
	clear(itdb[0x58:0x6c])
	binary.LittleEndian.PutUint16(itdb[0x30:0x32], 1) // hashing_scheme = ITDB_CHECKSUM_HASH58

	dig := computeHash58(fw[:8], itdb)
	copy(itdb[0x58:0x6c], dig[:])

	copy(itdb[0x18:0x20], dbID)
	copy(itdb[0x32:0x46], unk32)
	return nil
}

// DecodeGUID converts a hex GUID string (with or without "0x" prefix) into
// raw bytes. At most the first 8 bytes are used for HASH58.
func DecodeGUID(s string) ([]byte, error) {
	h := s
	if len(h) >= 2 && (h[0] == '0' && (h[1] == 'x' || h[1] == 'X')) {
		h = h[2:]
	}
	if len(h) > 40 {
		return nil, fmt.Errorf("FireWire GUID string too long")
	}
	if len(h)%2 != 0 {
		return nil, fmt.Errorf("FireWire GUID has odd hex length")
	}
	out := make([]byte, len(h)/2)
	for i := 0; i < len(out); i++ {
		hi, ok1 := hexVal(h[2*i])
		lo, ok2 := hexVal(h[2*i+1])
		if !ok1 || !ok2 {
			return nil, fmt.Errorf("invalid hex in FireWire GUID")
		}
		out[i] = hi<<4 | lo
	}
	return out, nil
}

func hexVal(c byte) (byte, bool) {
	switch {
	case c >= '0' && c <= '9':
		return c - '0', true
	case c >= 'a' && c <= 'f':
		return c - 'a' + 10, true
	case c >= 'A' && c <= 'F':
		return c - 'A' + 10, true
	}
	return 0, false
}
